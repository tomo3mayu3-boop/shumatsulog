#!/usr/bin/env node
/* ============================================================
   Journey Intro Engine v2 ― 地図データビルド（実行はビルド時のみ・1回）
   GeoJSON(ステージ別LOD) → SVGパス化 → assets/journey/map-data/journey-map.v1.js

   前段（mapshaperでLOD別GeoJSONを生成。source:
     ・世界: Natural Earth 110m land (Public Domain)
     ・日本近海: 国土地理院「地球地図日本」v2.2 polbnda_jpn（出典表記必須）
   ）:
     npx -y mapshaper ne110/ne_110m_land.shp -simplify weighted 40% keep-shapes \
        -o format=geojson precision=0.1 out/world.json
     npx -y mapshaper polbnda_jpn.shp -dissolve2 -clip bbox=127,29.5,147,46.5 \
        -simplify weighted 5% keep-shapes -filter-islands min-area=4km2 \
        -o format=geojson precision=0.005 out/japan.json
     npx -y mapshaper polbnda_jpn.shp -dissolve2 -clip bbox=122,23,132.5,30 \
        -simplify weighted 22% keep-shapes -filter-islands min-area=1km2 \
        -o format=geojson precision=0.002 out/ryukyu.json
     npx -y mapshaper polbnda_jpn.shp -dissolve2 -clip bbox=124.55,24.55,125.75,25.15 \
        -simplify weighted 85% keep-shapes -o format=geojson precision=0.0005 out/miyako.json

   使い方: node scripts/build-map-data.mjs <geojsonディレクトリ>
   ============================================================ */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const SRC = process.argv[2];
if (!SRC) { console.error('usage: node scripts/build-map-data.mjs <dir with world/japan/ryukyu/miyako.json>'); process.exit(1); }

const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'assets', 'journey', 'map-data');
mkdirSync(OUT, { recursive: true });

/* ステージ定義: bbox(経緯度) と投影(equirect + cos(中央緯度)補正)。世界のみ素のequirect */
const STAGES = {
  world:  { file: 'world.json',  kind: 'equirect-world' },
  japan:  { file: 'japan.json',  bbox: [127, 29.5, 147, 46.5],       minRingArea: 2.0 },
  ryukyu: { file: 'ryukyu.json', bbox: [122, 23, 132.5, 30],         minRingArea: 1.2 },
  miyako: { file: 'miyako.json', bbox: [124.55, 24.55, 125.75, 25.15], minRingArea: 0.4 },
};
const W = 1000; // 各ステージの基準幅(viewBox units)

function project(stage) {
  if (stage.kind === 'equirect-world') {
    return { w: 1000, h: 500, fx: lon => (lon + 180) / 360 * 1000, fy: lat => (90 - lat) / 180 * 500 };
  }
  const [lonMin, latMin, lonMax, latMax] = stage.bbox;
  const midLat = (latMin + latMax) / 2 * Math.PI / 180;
  const k = Math.cos(midLat);
  const s = W / ((lonMax - lonMin) * k);
  return { w: W, h: Math.round((latMax - latMin) * s),
           fx: lon => (lon - lonMin) * k * s, fy: lat => (latMax - lat) * s };
}
function ringArea(pts) { let a = 0; for (let i = 0, n = pts.length; i < n; i++) { const [x1, y1] = pts[i], [x2, y2] = pts[(i + 1) % n]; a += x1 * y2 - x2 * y1; } return Math.abs(a / 2); }
function rings(geom) {
  if (!geom) return [];
  if (geom.type === 'Polygon') return geom.coordinates;
  if (geom.type === 'MultiPolygon') return geom.coordinates.flat();
  return [];
}
/* mapshaper出力は FeatureCollection / GeometryCollection の両方があり得る */
function geometries(gj) {
  if (gj.type === 'FeatureCollection') return gj.features.map(f => f.geometry);
  if (gj.type === 'GeometryCollection') return gj.geometries;
  return [gj];
}

const data = { version: 1, generated: new Date().toISOString().slice(0, 10),
  attribution: '地図データ: 国土地理院（地球地図日本）／Natural Earth', stages: {} };
let report = [];

for (const [name, st] of Object.entries(STAGES)) {
  const gj = JSON.parse(readFileSync(join(SRC, st.file), 'utf8'));
  const P = project(st);
  const paths = []; let pts = 0, dropped = 0;
  for (const g of geometries(gj)) for (const ring of rings(g)) {
    const proj = ring.map(([lon, lat]) => [P.fx(lon), P.fy(lat)]);
    if (proj.length < 4 || (st.minRingArea && ringArea(proj) < st.minRingArea)) { dropped++; continue; }
    let d = '', px = null, py = null;
    for (let i = 0; i < proj.length; i++) {
      const x = +proj[i][0].toFixed(1), y = +proj[i][1].toFixed(1);
      if (x === px && y === py) continue;
      d += (i === 0 ? 'M' : 'L') + x + ' ' + y; px = x; py = y; pts++;
    }
    paths.push(d + 'Z');
  }
  data.stages[name] = { viewBox: `0 0 ${P.w} ${P.h}`, paths,
    bbox: st.bbox || [-180, -90, 180, 90] };
  report.push(`${name}: rings=${paths.length} pts=${pts} dropped=${dropped} viewBox=0 0 ${P.w} ${P.h}`);
}

const js = `/* generated by scripts/build-map-data.mjs (${data.generated}) — 手編集禁止
   sources: 国土地理院「地球地図日本」v2.2 polbnda（要出典表記）/ Natural Earth 110m land (PD) */
window.JOURNEY_MAP_DATA = ${JSON.stringify(data)};
`;
writeFileSync(join(OUT, 'journey-map.v1.js'), js);
console.log(report.join('\n'));
console.log(`wrote ${join(OUT, 'journey-map.v1.js')} (${(js.length / 1024).toFixed(1)} KB raw)`);
